#requires -Version 7
<#
.SYNOPSIS
  Opens the pull request that publishes a released version of DikTap in microsoft/winget-pkgs.
.DESCRIPTION
  Generates the manifests for a version already published on GitHub (New-WingetManifest.ps1), pushes them to a branch of the
  fork <ForkOwner>/winget-pkgs and opens the PR against microsoft/winget-pkgs. Used by the release workflow.
  It only works once the package already exists in winget-pkgs (the first submission is done by hand), and it needs
  a token with the public_repo scope in GH_TOKEN (the fork lives under that account).
.EXAMPLE
  ./scripts/Submit-Winget.ps1 -Version 1.2.3 -DryRun   # prepares everything but pushes nothing
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Version,
    [string]$ForkOwner = 'jorgeju',
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$upstream = 'microsoft/winget-pkgs'
$identifier = 'jorgeju.DikTap'
$packagePath = 'manifests/j/jorgeju/DikTap'
$branch = "$identifier-$Version"

if (-not $env:GH_TOKEN) { throw 'GH_TOKEN is required (token with public_repo scope).' }

# The first version of a package is a "New package" PR with a manual review; this script only covers new versions.
gh api "repos/$upstream/contents/$packagePath" --silent 2>$null
if ($LASTEXITCODE -ne 0) { throw "$identifier is not in $upstream yet: submit the first version by hand." }

gh api "repos/$upstream/contents/$packagePath/$Version" --silent 2>$null
if ($LASTEXITCODE -eq 0) { Write-Host "$identifier $Version is already in $upstream; nothing to do."; return }

$openPrs = gh pr list --repo $upstream --state open --search "$identifier $Version in:title" --json url --jq '.[].url'
if ($openPrs) { Write-Host "There is already an open PR: $openPrs"; return }

& (Join-Path $PSScriptRoot 'New-WingetManifest.ps1') -Version $Version
if ($LASTEXITCODE -ne 0) { throw 'Could not generate the manifests.' }
$manifests = Join-Path $root "artifacts/winget/$packagePath/$Version"

$work = Join-Path ([IO.Path]::GetTempPath()) "winget-pkgs-$([guid]::NewGuid().ToString('N'))"
try {
    git clone --quiet --filter=blob:none --no-checkout --depth 1 "https://github.com/$upstream.git" $work
    if ($LASTEXITCODE -ne 0) { throw 'Could not clone winget-pkgs.' }
    Push-Location $work
    try {
        git sparse-checkout set --cone $packagePath
        git checkout --quiet -b $branch
        $dest = Join-Path $work "$packagePath/$Version"
        New-Item -ItemType Directory -Force $dest | Out-Null
        Copy-Item (Join-Path $manifests '*') $dest
        git add $packagePath
        git -c user.name='DikTap release' -c user.email='noreply@github.com' commit --quiet -m "New version: $identifier version $Version"

        if ($DryRun) { Write-Host "DryRun: branch $branch ready in $work, nothing pushed."; return }

        $auth = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes("x-access-token:$env:GH_TOKEN"))
        git -c "http.https://github.com/.extraheader=AUTHORIZATION: basic $auth" push --force "https://github.com/$ForkOwner/winget-pkgs.git" "${branch}:${branch}"
        if ($LASTEXITCODE -ne 0) { throw 'Could not push to the fork.' }
    }
    finally { Pop-Location }

    $body = @"
New version of **$identifier**: $Version

- Release: https://github.com/jorgeju/DikTap/releases/tag/v$Version
- Manifests generated by ``scripts/Submit-Winget.ps1`` and validated with ``winget validate``.
"@
    gh pr create --repo $upstream --head "${ForkOwner}:${branch}" --base master --title "New version: $identifier version $Version" --body $body
    if ($LASTEXITCODE -ne 0) { throw 'Could not open the PR.' }
}
finally {
    if (Test-Path $work) { Remove-Item $work -Recurse -Force -ErrorAction SilentlyContinue }
}
